import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { authorizeFoundryJdam, generateNflPlayoffPicks, nflBracketComplete, nflPlayoffGames, sanitizeNflPlayoffPicks } from "../src/lib/postseason/nfl-maps.ts";

const original = generateNflPlayoffPicks(1);
assert.equal(Object.keys(original).length, 13);
assert.equal(nflBracketComplete(original), true);
assert.equal(nflPlayoffGames(original).length, 13);
assert.deepEqual(sanitizeNflPlayoffPicks(original), original);
const strike = authorizeFoundryJdam(original);
assert.equal(nflBracketComplete(strike.picks), true);
assert.equal(strike.targets.length, 3);
assert.ok(strike.changedCount >= 3);
const zeroPickStrike = authorizeFoundryJdam({});
assert.equal(nflBracketComplete(zeroPickStrike.picks), true);
assert.equal(zeroPickStrike.changedCount, 13);
assert.equal(zeroPickStrike.targets.length, 3);
const ui = readFileSync("src/components/FoundryNflActThree.tsx", "utf8");
const preview = readFileSync("src/app/foundry/preview/page.tsx", "utf8");
assert.match(ui, /NFL playoff bracket converging on the Super Bowl/);
assert.match(ui, /AFC advances right/);
assert.match(ui, /NFC advances left/);
assert.match(ui, /Conference champions converge here/);
assert.match(ui, /1-seeds enter in the Divisional Round/);
assert.match(ui, /Computer assumes command/);
assert.match(ui, /weapon-unstable/);
assert.match(ui, /NO HUMAN TARGET ON FILE/);
assert.match(ui, /computer made and locked all 13 decisions/i);
assert.match(ui, /humanPickCount/);
assert.match(ui, /authorizationWeek: seasonWeek/);
assert.doesNotMatch(ui, /JDAM ARMS AFTER THE FULL BRACKET/);
assert.match(preview, /state\.sport === "nfl"[\s\S]*Season status" value="PHASE III"[\s\S]*FoundryNflActThree/);
assert.match(preview, /onRegular=\{\(\) => \{[\s\S]*localStorage\.removeItem\("warroom-foundry-nfl-maps-v1"\)/);
const walkthrough = readFileSync("src/lib/foundry-walkthrough.ts", "utf8");
assert.match(walkthrough, /sport === "nfl" \? 22/);
assert.match(preview, /REGULAR SEASON COMPLETE → PHASE II · SEEDS LOCKED/);
assert.match(preview, /jdam\.authorizationWeek === active/);
assert.match(preview, /const cutWeek = foundryPostseasonStartWeek\(state\.sport\)/);
assert.doesNotMatch(preview, /state\.sport === "nfl" \? 18/);

console.log("NFL JDAM verified: available at decision zero · partial picks preserved · 14-team field · divisional reseeding · three-impact reveal · complete computer bracket");
